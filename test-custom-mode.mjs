import { chromium } from 'playwright';

const origin = 'http://localhost:4174';
const browserPath = 'C:/Users/Castbox/.workbuddy/browsers/neon-turf/chromium-1234/chrome-win64/chrome.exe';
const browser = await chromium.launch({ headless: true, executablePath: browserPath });
const errors = [];
const failures = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin, { waitUntil: 'networkidle' });
  await page.waitForSelector('[data-action="start"]');
  await page.click('[data-arena="custom"]');
  await page.waitForSelector('[data-custom-grid]');
  const initialGrid = await page.locator('[data-custom-grid] .grid-cell').count();
  await page.click('[data-block-kind="high"]');
  await page.locator('[data-custom-grid] .grid-cell').nth(53).click();
  await page.locator('[data-custom-grid] .grid-cell').nth(66).click();
  await page.selectOption('[data-custom="worldSize"]', '84');
  await page.selectOption('[data-custom="teamSize"]', '3');
  await page.selectOption('[data-custom="teamCount"]', '4');
  await page.selectOption('[data-custom-rule="matchSeconds"]', '60');
  await page.locator('[data-custom-rule="allowDamage"]').uncheck();
  await page.locator('[data-custom-start]').click();
  await page.waitForSelector('#game-canvas');
  await page.waitForTimeout(1300);
  const state = await page.evaluate(() => window.__neonDebug?.state());
  const hudTeams = await page.locator('.hud-top .team-score').count();
  const gridFilled = await page.evaluate(() => JSON.parse(localStorage.getItem('neon-turf-save') || '{}').customMode);
  if (initialGrid !== 144) failures.push(`grid cells=${initialGrid}`);
  if (state?.arena !== 'custom') failures.push(`arena=${state?.arena}`);
  if (state?.worldSize !== 84) failures.push(`worldSize=${state?.worldSize}`);
  if (state?.teamSize !== 3) failures.push(`teamSize=${state?.teamSize}`);
  if (state?.fighterCount !== 12) failures.push(`fighterCount=${state?.fighterCount}`);
  if (hudTeams !== 4) failures.push(`hudTeams=${hudTeams}`);
  if (gridFilled?.teamCount !== 4 || gridFilled?.teamSize !== 3 || gridFilled?.worldSize !== 84) failures.push(`custom save=${JSON.stringify(gridFilled)}`);
  if (gridFilled?.blocks?.length !== 2) failures.push(`blocks=${gridFilled?.blocks?.length}`);
  if (gridFilled?.rules?.allowDamage !== false) failures.push('allowDamage rule did not persist');
  await page.click('[data-pause]');
  await page.waitForSelector('[data-quit]');
  await page.click('[data-quit]');
  await page.waitForSelector('[data-arena="custom"]');
  await page.click('[data-arena="custom"]');
  await page.waitForSelector('[data-custom-grid]');
  await page.selectOption('[data-custom="teamSize"]', '20');
  await page.selectOption('[data-custom="teamCount"]', '6');
  await page.locator('[data-custom-start]').click();
  await page.waitForSelector('#game-canvas');
  await page.waitForTimeout(700);
  const stress = await page.evaluate(() => window.__neonDebug?.state());
  const stressHudTeams = await page.locator('.hud-top .team-score').count();
  if (stress?.teamSize !== 20 || stress?.fighterCount !== 120) failures.push(`stress fighters=${stress?.fighterCount}, teamSize=${stress?.teamSize}`);
  if (stress?.teams?.length !== 6 || stressHudTeams !== 6) failures.push(`stress teams=${JSON.stringify(stress?.teams)}, hud=${stressHudTeams}`);
  if (errors.length) failures.push(...errors);
  console.log(JSON.stringify({ initialGrid, hudTeams, state: { arena: state?.arena, worldSize: state?.worldSize, teamSize: state?.teamSize, fighterCount: state?.fighterCount, teams: state?.teams, rules: state?.rules }, stress: { teamSize: stress?.teamSize, fighterCount: stress?.fighterCount, teams: stress?.teams, hudTeams: stressHudTeams }, customMode: gridFilled, errors, failures }, null, 2));
  if (failures.length) process.exitCode = 1;
} finally {
  await browser.close();
}
